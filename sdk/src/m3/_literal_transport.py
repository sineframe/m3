"""Structural local-IPC boundary; implementations retain native I/O ownership."""

from __future__ import annotations

from types import TracebackType
from typing import Protocol


class BootstrapChannel(Protocol):
    def settimeout(self, seconds: float) -> None: ...
    def recv(self, size: int) -> bytes: ...
    def sendall(self, data: bytes) -> None: ...
    def shutdown(self, how: int) -> None: ...
    def close(self) -> None: ...
    def __enter__(self) -> BootstrapChannel: ...
    def __exit__(
        self,
        kind: type[BaseException] | None,
        value: BaseException | None,
        traceback: TracebackType | None,
    ) -> None: ...


class BootstrapListener(Protocol):
    def accept(self) -> tuple[BootstrapChannel, object]: ...
    def close(self) -> None: ...
