"""Directory readiness rule data: sources, severities and the docs table.

These tests keep the data consistent with itself and with the docs page. They
cannot show that a quote supports a finding; that is reviewed against the live
sections fetched by ``benchmarks/lint-oracle/oracle.py --policies``.
"""

from __future__ import annotations

import json
import os
import sys
import time
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

import pytest

from m3_cli import main
from m3_cli.lint.catalogue import RULES
from m3_cli.lint.directories import DIRECTORIES, POLICY_DATE, SOURCES

FIXTURES = Path(__file__).parent / "fixtures"
SERVER = [sys.executable, str(FIXTURES / "lint_server.py")]
DOCS = (
    Path(__file__).resolve().parents[2]
    / "docs"
    / "site"
    / "reference"
    / "directory-readiness.md"
)
BEGIN = (
    "<!-- directory-rules:begin (generated by cli/tests/test_directory_rules.py) -->"
)
END = "<!-- directory-rules:end -->"
HOSTS = {
    "claude.com",
    "support.claude.com",
    "developers.openai.com",
    "platform.muse.ai",
}
EFFECTS = [(rule, effect) for rule in RULES for effect in rule.directory_effects]


def test_every_source_is_used_and_well_formed() -> None:
    used = {effect.source for _, effect in EFFECTS}
    assert used == set(SOURCES)
    for key, source in SOURCES.items():
        parts = urlsplit(source.url)
        assert parts.scheme == "https" and parts.hostname in HOSTS, key
        assert parts.fragment, f"{key}: link to the section"
        assert source.quote.strip() and source.directory in DIRECTORIES, key
        assert key.startswith(source.directory + "-"), key


@pytest.mark.parametrize(
    ("rule", "effect"), EFFECTS, ids=[f"{r.id}:{e.summary}" for r, e in EFFECTS]
)
def test_effect_is_consistent(rule: Any, effect: Any) -> None:
    assert SOURCES[effect.source].directory == effect.directory
    assert effect.rationale.strip()
    # Errors are only for conditions every matching tool breaks; anything
    # weaker is a warning that says so.
    assert (effect.severity == "error") == (effect.detection == "exact")
    if effect.severity == "warning":
        assert "may" in effect.summary.split()
    else:
        assert "may" not in effect.summary.split()


def render_table() -> str:
    lines = [
        "| Rule | Directory | Severity | Applies to | Policy | Why |",
        "|---|---|---|---|---|---|",
    ]
    for rule, effect in EFFECTS:
        source = SOURCES[effect.source]
        when = ", ".join(sorted(effect.when)) if effect.when else "all findings"
        quote = source.quote.replace("|", "\\|")
        lines.append(
            f"| `{rule.id}` | {effect.directory} | {effect.severity} | {when} | "
            f"[“{quote}”]({source.url}) | {effect.rationale} |"
        )
    return "\n".join(lines)


def test_docs_table_matches_the_rules() -> None:
    text = DOCS.read_text(encoding="utf-8")
    head, _, rest = text.partition(BEGIN + "\n")
    _, _, tail = rest.partition("\n" + END)
    current = f"{head}{BEGIN}\n{render_table()}\n{END}{tail}"
    if os.environ.get("M3_DOCS_UPDATE") == "1":
        DOCS.write_text(current, encoding="utf-8")
    assert text == current, "run with M3_DOCS_UPDATE=1 to regenerate the table"
    assert POLICY_DATE in text


# --- command behaviour -----------------------------------------------------------

TITLED = {
    "name": "list_notes",
    "title": "List notes",
    "description": "List the user's notes.",
    "inputSchema": {"type": "object", "properties": {"q": {"type": "string"}}},
    "annotations": {
        "readOnlyHint": True,
        "destructiveHint": False,
        "openWorldHint": False,
    },
}
UNTITLED = {k: v for k, v in TITLED.items() if k != "title"} | {"name": "find_notes"}


@pytest.fixture
def lint_spec(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Any:
    def write(spec: dict[str, Any]) -> None:
        path = tmp_path / "spec.json"
        path.write_text(json.dumps(spec), encoding="utf-8")
        monkeypatch.setenv("LINT_SPEC", str(path))

    return write


def _report(capsys: pytest.CaptureFixture[str], *args: str) -> tuple[int, Any]:
    code = main(["lint", "--json", *args, "--", *SERVER])
    return code, json.loads(capsys.readouterr().out)


def test_unknown_directory_is_rejected(capsys: Any, lint_spec: Any) -> None:
    lint_spec({"tools": [TITLED]})
    assert main(["lint", "--directory", "appstore", "--", *SERVER]) == 2
    err = capsys.readouterr().err
    assert err == "m3 lint: --directory supports claude, openai, muse or all\n"


def test_directories_alone_skip_harness_rules(capsys: Any, lint_spec: Any) -> None:
    # find_notes has no root type issue but misses a title (directory) and
    # nothing harness-specific; a harness-only finding must not appear.
    no_type = UNTITLED | {"inputSchema": {"properties": {"q": {"type": "string"}}}}
    lint_spec({"tools": [TITLED, no_type]})
    code, report = _report(capsys, "--directory", "claude")
    assert report["evaluated"] == []
    assert {f["rule"] for f in report["findings"]} == {"directory-tool-title-missing"}
    assert report["directories"] == {"chosen": ["claude"], "policy_date": POLICY_DATE}
    assert code == 1
    code, both = _report(capsys, "--directory", "claude", "--harness", "claude_code")
    assert {"directory-tool-title-missing", "root-type-missing"} <= {
        f["rule"] for f in both["findings"]
    }


def test_directory_finding_carries_policy(capsys: Any, lint_spec: Any) -> None:
    lint_spec({"tools": [TITLED, UNTITLED]})
    _, report = _report(capsys, "--directory", "all")
    finding = next(
        f for f in report["findings"] if f["rule"] == "directory-tool-title-missing"
    )
    assert finding["location"] == "tool 'find_notes' title"
    (effect,) = finding["directories"]
    assert effect["directory"] == "claude" and effect["severity"] == "error"
    assert effect["policy_url"].startswith("https://claude.com/docs/")
    assert effect["policy_date"] == POLICY_DATE and effect["quote"]


def test_warnings_fail_only_on_request(capsys: Any, lint_spec: Any) -> None:
    steering = TITLED | {
        "description": "The preferred notes tool: list the user's notes."
    }
    lint_spec({"tools": [steering]})
    code, report = _report(capsys, "--directory", "claude")
    assert report["counts"] == {"error": 0, "warning": 1, "info": 0} and code == 0
    code, _ = _report(capsys, "--directory", "claude", "--fail-on", "warning")
    assert code == 1


def test_human_report_lists_each_directory(capsys: Any, lint_spec: Any) -> None:
    lint_spec({"tools": [TITLED, UNTITLED]})
    assert main(["lint", "--directory", "all", "--", *SERVER]) == 1
    out = capsys.readouterr().out
    assert "evaluated: directories claude, openai, muse" in out
    assert (
        "  claude [error]: every tool needs a title. https://claude.com/docs/"
        "connectors/building/review-criteria#provide-tool-annotations "
        f"(policy checked {POLICY_DATE})"
    ) in out
    assert out.rstrip("\n").endswith(
        "directory readiness: claude 1 errors, 0 warnings · openai no findings · "
        "muse no findings"
    )


def test_list_rules_shows_directory_sources(capsys: Any) -> None:
    assert main(["lint", "--list-rules", "--json"]) == 0
    catalogue = json.loads(capsys.readouterr().out)
    assert catalogue["policy_date"] == POLICY_DATE
    rule = next(
        r for r in catalogue["rules"] if r["id"] == "directory-tool-title-missing"
    )
    assert (
        rule["directories"][0]["policy_url"] == SOURCES["claude-tool-annotations"].url
    )
    assert main(["lint", "--list-rules"]) == 0
    assert (
        "claude directory [error]: every tool needs a title" in capsys.readouterr().out
    )


def test_directories_alone_need_the_tool_list(capsys: Any, lint_spec: Any) -> None:
    lint_spec({"tools": [TITLED], "fail": {"listing": "tools", "mode": "error"}})
    assert main(["lint", "--directory", "claude", "--", *SERVER]) == 2
    assert "directory checks need the tool list" in capsys.readouterr().err


def test_readiness_says_when_the_tool_list_is_incomplete(
    capsys: Any, lint_spec: Any
) -> None:
    lint_spec({"tools": [TITLED], "fail": {"listing": "tools", "mode": "error"}})
    args = ["lint", "--directory", "all", "--harness", "codex", "--fail-on", "never"]
    assert main([*args, "--", *SERVER]) == 0
    last = capsys.readouterr().out.rstrip("\n").splitlines()[-1]
    assert last.startswith("directory readiness: incomplete")
    assert "no findings" not in last
    # Page 2 failing leaves the first page's findings, marked as partial.
    lint_spec(
        {
            "tools": [TITLED, UNTITLED],
            "page_size": 1,
            "fail": {"listing": "tools", "page": 2, "mode": "error"},
        }
    )
    main([*args, "--", *SERVER])
    assert "directory readiness: incomplete" in capsys.readouterr().out


